// Deterministic PRNG (mulberry32) -- same seed always produces the same
// sequence, so the demo's 365-day dataset is stable across reloads/renders
// instead of re-randomizing every time. This is a visual-reference demo
// route only (see data/review-demo-data.ts's header) -- never used for the
// real, Supabase-backed Review page.
export function mulberry32(seed: number): () => number {
  let a = seed;
  return function () {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function hashString(s: string): number {
  let h = 0;
  for (let i = 0; i < s.length; i++) {
    h = (Math.imul(31, h) + s.charCodeAt(i)) | 0;
  }
  return h >>> 0;
}
